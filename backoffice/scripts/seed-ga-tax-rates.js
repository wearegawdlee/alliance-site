async function run() {
  const client = await pool.connect();

  try {
    await client.query('BEGIN');

    await client.query(
      `DELETE FROM tax_rates WHERE state='GA' AND effective_start_date=$1`,
      [EFFECTIVE_START_DATE],
    );

    await client.query(`
      INSERT INTO tax_rates(state, county, city, postal_code, rate, effective_start_date, is_active)
      VALUES('GA', 'Default', NULL, NULL, 0, $1, true)
    `, [EFFECTIVE_START_DATE]);

    for (const [code, county, city, rate] of rates) {
      await client.query(`
        INSERT INTO tax_rates(state, county, city, postal_code, rate, effective_start_date, is_active)
        VALUES('GA', $1, $2, NULL, $3, $4, true)
      `, [county, city, rate, EFFECTIVE_START_DATE]);
    }

    await client.query('COMMIT');
    console.log(`Seeded ${rates.length} Georgia tax rates from ${SOURCE}.`);
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
